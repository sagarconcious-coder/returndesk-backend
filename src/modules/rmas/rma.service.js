// E) approveRma(id)
// → sets RMA status to APPROVED — only allowed while it's still PENDING
export const approveRma = async (id) => {
  const existing = await getRmaByIdFromRepo(id);
  if (!existing) {
    const error = new Error("RMA not found");
    error.statusCode = 404;
    throw error;
  }
  if (existing.status !== RMA_STATUS.PENDING) {
    const error = new Error(
      `Cannot approve — RMA status is already ${existing.status}`,
    );
    error.statusCode = 409;
    throw error;
  }

  const rma = await updateRmaStatus(id, RMA_STATUS.APPROVED, null);
  if (!rma) {
    const error = new Error("Cannot approve — RMA status changed concurrently");
    error.statusCode = 409;
    throw error;
  }
  await notifyRmaApproved(rma);
  return rma;
};

// F) rejectRma(id, reason)
// → sets RMA status to REJECTED with a reason — only allowed while it's still PENDING
export const rejectRma = async (id, reason) => {
  const existing = await getRmaByIdFromRepo(id);
  if (!existing) {
    const error = new Error("RMA not found");
    error.statusCode = 404;
    throw error;
  }
  if (existing.status !== RMA_STATUS.PENDING) {
    const error = new Error(
      `Cannot reject — RMA status is already ${existing.status}`,
    );
    error.statusCode = 409;
    throw error;
  }

  const rma = await updateRmaStatus(id, RMA_STATUS.REJECTED, reason);
  if (!rma) {
    const error = new Error("Cannot reject — RMA status changed concurrently");
    error.statusCode = 409;
    throw error;
  }
  await notifyRmaRejected(rma);
  return rma;
};

// G)  getShippingEstimateForDealer(dealer_id)
// → looks up the dealer's pincode and asks Shiprocket for the cheapest return-shipment rate to the warehouse

export const getShippingEstimateForDealer = async (dealer_id) => {
  const dealer = await getDealerById(dealer_id);
  if (!dealer) {
    const error = new Error("Dealer not found");
    error.statusCode = 404;
    throw error;
  }

  return getShippingEstimate({
    pickupPincode: dealer.pincode,
    deliveryPincode: process.env.WAREHOUSE_PINCODE,
  });
};
